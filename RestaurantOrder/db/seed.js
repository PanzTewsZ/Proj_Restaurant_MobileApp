// ข้อมูลตั้งต้น: 5 หมวด x 5 รายการ = 25 เมนู, 15 โต๊ะ (ราคาเป็นบาท แปลงเป็นสตางค์ตอนใส่)
const MENU = [
  ['อาหารจานเดียว', [['ผัดกะเพราหมูสับ', 60], ['ข้าวผัดกุ้ง', 70], ['ข้าวมันไก่', 55], ['ผัดซีอิ๊วหมู', 60], ['ข้าวไข่เจียวหมูสับ', 50]]],
  ['ต้ม/แกง', [['ต้มยำกุ้ง', 120], ['แกงเขียวหวานไก่', 90], ['ต้มข่าไก่', 90], ['แกงส้มชะอมกุ้ง', 100], ['ต้มจืดเต้าหู้หมูสับ', 70]]],
  ['ของทอด/ยำ', [['ไก่ทอด', 80], ['ปลาทอดกระเทียม', 150], ['ยำวุ้นเส้น', 90], ['ส้มตำไทย', 60], ['หมูทอดกระเทียม', 90]]],
  ['เครื่องดื่ม', [['น้ำเปล่า', 10], ['ชาไทยเย็น', 35], ['กาแฟเย็น', 40], ['น้ำมะนาวโซดา', 35], ['น้ำส้มคั้น', 45]]],
  ['ของหวาน', [['ข้าวเหนียวมะม่วง', 90], ['บัวลอย', 50], ['ไอศกรีมกะทิ', 45], ['ทับทิมกรอบ', 45], ['เฉาก๊วยนมสด', 40]]],
];

export async function seed(db) {
  for (const [cat, items] of MENU) {
    const r = await db.runAsync('INSERT INTO categories (name) VALUES (?)', [cat]);
    for (const [name, baht] of items) {
      await db.runAsync(
        'INSERT INTO menu_items (category_id, name, price_satang) VALUES (?, ?, ?)',
        [r.lastInsertRowId, name, baht * 100]
      );
    }
  }
  for (let i = 1; i <= 15; i++) {
    await db.runAsync('INSERT INTO dining_tables (label) VALUES (?)', [String(i)]);
  }
}
